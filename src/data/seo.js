// Per-route metadata and JSON-LD. Used by the prerender script (static <head>)
// and by usePageMeta on client-side navigation. Only verifiable facts are
// included — no ratings, review counts, opening hours or street address.

import { SITE_URL, site, fullAddress, mapLinkUrl } from './site.js';
import { brand, clinicVideo, studioVideo, treatmentMedia } from './media.js';
import { featuredTestimonial } from './testimonials.js';
import { categories, categoryPath, getCategory, treatments, treatmentsIn, treatmentPath } from './treatments.js';

const BUSINESS_ID = `${SITE_URL}/#business`;
const ORG_ID = `${SITE_URL}/#organization`;
const abs = (path) => `${SITE_URL}${path}`;

// 1200×630 social-share images (generated by scripts/og-images.py from the page's own photos).
const OG = (name) => `/images/og/${name}.jpg`;
const TREATMENT_OG = new Set(Object.keys(treatmentMedia));
const ogForTreatment = (t) => (TREATMENT_OG.has(t.slug) ? OG(`treatment-${t.slug}`) : OG(`category-${t.category}`));

const organization = () => ({
  '@type': 'Organization',
  '@id': ORG_ID,
  name: site.name,
  url: abs('/'),
  logo: abs(brand.logo.src),
  email: site.email,
  sameAs: [site.social.facebook, site.social.instagram, site.social.tiktok],
});

const business = () => ({
  '@type': 'BeautySalon',
  '@id': BUSINESS_ID,
  name: site.name,
  description:
    'Hera Wellness Studio is a beauty and wellness studio in Diliman, Quezon City, Metro Manila, offering facial, body and hair treatments with personalized care. Online reservations only.',
  slogan: 'Where beauty meets wellness',
  url: abs('/'),
  logo: abs(brand.logo.src),
  image: abs(brand.ogImage),
  email: site.email,
  parentOrganization: { '@id': ORG_ID },
  address: {
    '@type': 'PostalAddress',
    ...(site.location.street && { streetAddress: site.location.street }),
    addressLocality: site.location.locality,
    addressRegion: site.location.region,
    postalCode: site.location.postalCode,
    addressCountry: site.location.country,
  },
  geo: { '@type': 'GeoCoordinates', latitude: site.location.lat, longitude: site.location.lng },
  hasMap: mapLinkUrl,
  areaServed: 'Quezon City, Metro Manila',
  currenciesAccepted: 'PHP',
  paymentAccepted: 'All payment methods',
  sameAs: [site.social.facebook, site.social.instagram, site.social.tiktok],
});

const serviceId = (t) => abs(`${treatmentPath(t)}#service`);

const service = (t) => ({
  '@type': 'Service',
  '@id': serviceId(t),
  name: t.name,
  ...(t.aka && { alternateName: t.aka }),
  serviceType: getCategory(t.category).name,
  category: getCategory(t.category).name,
  ...((t.summary || t.details) && { description: [t.summary, t.details].filter(Boolean).join(' ') }),
  url: abs(treatmentPath(t)),
  // Only genuine photos go into structured data.
  ...(t.image && !t.image.generated && { image: abs(t.image.src) }),
  provider: { '@id': BUSINESS_ID },
  areaServed: 'Quezon City, Metro Manila',
});

const testimonialVideo = () => ({
  '@type': 'VideoObject',
  '@id': abs('/reviews/#video'),
  name: featuredTestimonial.video.title,
  description: `${featuredTestimonial.name} (${featuredTestimonial.role}) talks about her experience at Hera Wellness Studio, including HIFU and HydraFacial treatments.`,
  thumbnailUrl: abs(featuredTestimonial.video.poster),
  contentUrl: abs(featuredTestimonial.video.src),
  uploadDate: featuredTestimonial.uploadDate,
  duration: featuredTestimonial.video.duration,
  transcript: featuredTestimonial.transcript.join(' '),
  publisher: { '@id': ORG_ID },
});

const studioVideoNode = () =>
  studioVideo && {
    '@type': 'VideoObject',
    '@id': abs('/about/#video'),
    name: studioVideo.title,
    description: 'A short walk-through from the surrounding complex to the entrance and reception of Hera Wellness Studio in Diliman, Quezon City.',
    thumbnailUrl: abs(studioVideo.poster),
    contentUrl: abs(studioVideo.src),
    uploadDate: featuredTestimonial.uploadDate,
    duration: studioVideo.duration,
    publisher: { '@id': ORG_ID },
  };

const clinicVideoNode = () => ({
  '@type': 'VideoObject',
  '@id': abs('/#clinic-video'),
  name: clinicVideo.title,
  description: 'A short film of Hera Wellness Studio in Diliman, Quezon City: the reception, interiors and treatment rooms.',
  thumbnailUrl: abs(clinicVideo.poster),
  contentUrl: abs(clinicVideo.src),
  uploadDate: featuredTestimonial.uploadDate,
  duration: clinicVideo.duration,
  publisher: { '@id': ORG_ID },
});

const breadcrumbs = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, path], i) => ({ '@type': 'ListItem', position: i + 1, name, item: abs(path) })),
});

const graph = (...nodes) => ({ '@context': 'https://schema.org', '@graph': nodes.filter(Boolean) });

const page = (type, path, name) => ({ '@type': type, '@id': abs(path), url: abs(path), name, isPartOf: { '@id': `${SITE_URL}/#website` }, about: { '@id': BUSINESS_ID } });

export function getPageMeta(pathname) {
  const path = pathname.endsWith('/') ? pathname : `${pathname}/`;
  const parts = path.split('/').filter(Boolean);

  if (path === '/') {
    return {
      title: 'Hera Wellness Studio | Facial, Body & Hair Treatments in Quezon City',
      description:
        'Rejuvenate, refresh, and restore at Hera Wellness Studio in Diliman, Quezon City. Thermage, HIFU, Pico Laser, HydraFacial, Cryo Fat Freeze, Diode Hair Removal and more — explore treatments and book online.',
      path,
      image: OG('studio'),
      jsonLd: graph(
        { '@type': 'WebSite', '@id': `${SITE_URL}/#website`, url: abs('/'), name: site.name, publisher: { '@id': ORG_ID } },
        organization(),
        clinicVideoNode(),
        {
          ...business(),
          hasOfferCatalog: {
            '@type': 'OfferCatalog',
            name: 'Treatments',
            itemListElement: categories.map((c) => ({
              '@type': 'OfferCatalog',
              name: c.name,
              url: abs(categoryPath(c.slug)),
              itemListElement: treatmentsIn(c.slug).map((t) => ({ '@type': 'Offer', itemOffered: service(t) })),
            })),
          },
        },
      ),
    };
  }

  if (path === '/treatments/') {
    return {
      title: 'Treatments | Hera Wellness Studio, Quezon City',
      description: `The full treatment menu of Hera Wellness Studio, ${fullAddress}: ${treatments.length} facial, body and hair treatments, each with photos and details. Book online.`,
      path,
      image: OG('treatments'),
      jsonLd: graph(
        breadcrumbs([['Home', '/'], ['Treatments', '/treatments/']]),
        {
          '@type': 'ItemList',
          name: `Treatments at ${site.name}`,
          itemListElement: treatments.map((t, i) => ({ '@type': 'ListItem', position: i + 1, url: abs(treatmentPath(t)), name: t.name })),
        },
        business(),
      ),
    };
  }

  if (parts[0] === 'treatments' && parts.length === 2) {
    const category = getCategory(parts[1]);
    if (category) {
      return {
        title: `${category.name} in Quezon City | Hera Wellness Studio`,
        description: category.seoDescription,
        path,
        image: OG(`category-${category.slug}`),
        jsonLd: graph(
          breadcrumbs([['Home', '/'], ['Treatments', '/treatments/'], [category.name, path]]),
          {
            '@type': 'ItemList',
            name: `${category.name} at ${site.name}`,
            itemListElement: treatmentsIn(category.slug).map((t, i) => ({ '@type': 'ListItem', position: i + 1, item: service(t) })),
          },
          business(),
        ),
      };
    }
  }

  if (parts[0] === 'treatments' && parts.length === 3) {
    const t = treatments.find((x) => x.category === parts[1] && x.slug === parts[2]);
    if (t) {
      const category = getCategory(t.category);
      const lead = t.summary ?? t.details ?? `${t.name} is one of the ${category.name.toLowerCase()} at Hera Wellness Studio.`;
      return {
        title: `${t.name} in Quezon City | Hera Wellness Studio`,
        description: `${lead} ${t.name} at Hera Wellness Studio, Diliman, Quezon City. Book online or request a consultation call.`.slice(0, 300),
        path,
        image: ogForTreatment(t),
        jsonLd: graph(
          breadcrumbs([['Home', '/'], ['Treatments', '/treatments/'], [category.name, categoryPath(category.slug)], [t.name, path]]),
          service(t),
          business(),
        ),
      };
    }
  }

  if (path === '/about/') {
    return {
      title: 'About Hera Wellness Studio | Beauty & Wellness in Diliman, Quezon City',
      description:
        'Hera Wellness Studio was founded to create a sanctuary where beauty, health and self-care come together. Meet the studio in Diliman, Quezon City, and see inside.',
      path,
      image: OG('about'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['About', path]]), page('AboutPage', path, `About ${site.name}`), clinicVideoNode(), studioVideoNode(), organization(), business()),
    };
  }

  if (path === '/reviews/') {
    return {
      title: 'Client Reviews & Video Testimonial | Hera Wellness Studio',
      description: `Watch ${featuredTestimonial.name} describe her experience at Hera Wellness Studio — HIFU, HydraFacial and a very personalized wellness journey. Full transcript included.`,
      path,
      image: OG('reviews'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Reviews', path]]), page('WebPage', path, 'Client reviews'), testimonialVideo(), business()),
    };
  }

  if (path === '/contact/') {
    return {
      title: 'Contact & Booking | Hera Wellness Studio, Quezon City',
      description: `Book a treatment at Hera Wellness Studio, ${fullAddress}. Request a consultation call or book a date and time online. Online reservations only.`,
      path,
      image: OG('contact'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Contact', path]]), page('ContactPage', path, `Contact ${site.name}`), business()),
    };
  }

  if (path === '/sitemap/') {
    return {
      title: 'Sitemap — All Pages & Treatments | Hera Wellness Studio',
      description: `Every page on the Hera Wellness Studio website: studio information, reviews, contact and all ${treatments.length} treatments.`,
      path,
      image: OG('studio'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Sitemap', path]]), page('WebPage', path, 'Sitemap')),
    };
  }

  return {
    title: 'Page not found | Hera Wellness Studio',
    description: 'The page you were looking for could not be found.',
    path,
    noindex: true,
  };
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function renderHead(meta) {
  const url = abs(meta.path);
  const image = abs(meta.image ?? brand.ogImage);
  return [
    `<title>${esc(meta.title)}</title>`,
    `<meta name="description" content="${esc(meta.description)}" />`,
    meta.noindex
      ? '<meta name="robots" content="noindex, follow" />'
      : `<meta name="robots" content="index, follow, max-image-preview:large" />
    <link rel="canonical" href="${url}" />`,
    '<meta property="og:type" content="website" />',
    `<meta property="og:site_name" content="${esc(site.name)}" />`,
    `<meta property="og:title" content="${esc(meta.title)}" />`,
    `<meta property="og:description" content="${esc(meta.description)}" />`,
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:image" content="${image}" />`,
    `<meta property="og:image:alt" content="${esc(meta.title)}" />`,
    ...(meta.image ? ['<meta property="og:image:width" content="1200" />', '<meta property="og:image:height" content="630" />'] : []),
    '<meta property="og:locale" content="en_PH" />',
    '<meta name="twitter:card" content="summary_large_image" />',
    `<meta name="twitter:title" content="${esc(meta.title)}" />`,
    `<meta name="twitter:description" content="${esc(meta.description)}" />`,
    `<meta name="twitter:image" content="${image}" />`,
    meta.jsonLd && `<script type="application/ld+json">${JSON.stringify(meta.jsonLd).replace(/</g, '\\u003c')}</script>`,
  ]
    .filter(Boolean)
    .join('\n    ');
}
