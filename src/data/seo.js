const breadcrumbs = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, path], i) => ({ '@type': 'ListItem', position: i + 1, name, item: abs(path) })),
});

// Every page carries the WebSite node, so its isPartOf reference resolves within the page.
const graph = (...nodes) => ({ '@context': 'https://schema.org', '@graph': [website(), ...nodes.filter(Boolean)] });

const page = (type, path, name, extra = {}) => ({
  '@type': type,
  '@id': abs(path),
  url: abs(path),
  name,
  inLanguage: LANG,
  isPartOf: { '@id': WEBSITE_ID },
  about: { '@id': BUSINESS_ID },
  ...extra,
});

export function getPageMeta(pathname) {
  const path = pathname.endsWith('/') ? pathname : `${pathname}/`;
  const parts = path.split('/').filter(Boolean);

  if (path === '/') {
    return {
      title: 'Hera Wellness Studio | Facial, Body & Hair Care, Quezon City',
      description:
        'Beauty & wellness studio in Diliman, Quezon City: Thermage, HIFU, Pico Laser, HydraFacial, Cryo Fat Freeze, laser hair removal and more. Book online.',
      path,
      image: OG('studio'),
      jsonLd: graph(
        page('WebPage', path, site.name),
        faqJsonLd(studioFaqs, abs('/#faq')),
        organization(),
        clinicVideoNode(),
        {
          ...business(),
          hasOfferCatalog: {
            '@type': 'OfferCatalog',
            name: 'Treatments',
            itemListElement: categories.map((c) => ({
              '@type': 'OfferCatalog',
              name: c.name,
              url: abs(categoryPath(c.slug)),
              itemListElement: treatmentsIn(c.slug).map((t) => ({ '@type': 'Offer', itemOffered: service(t) })),
            })),
          },
        },
      ),
    };
  }

  if (path === '/treatments/') {
    return {
      title: 'Treatments | Hera Wellness Studio, Quezon City',
      description: `All ${treatments.length} facial, body and hair treatments at Hera Wellness Studio, Diliman, Quezon City — each with photos and details. Book online.`,
      path,
      image: OG('treatments'),
      jsonLd: graph(
        breadcrumbs([['Home', '/'], ['Treatments', '/treatments/']]),
        {
          '@type': 'ItemList',
          name: `Treatments at ${site.name}`,
          itemListElement: treatments.map((t, i) => ({ '@type': 'ListItem', position: i + 1, url: abs(treatmentPath(t)), name: t.name })),
        },
        business(),
      ),
    };
  }

  if (parts[0] === 'treatments' && parts.length === 2) {
    const category = getCategory(parts[1]);
    if (category) {
      const lead = `${category.name} at Hera Wellness Studio, Diliman, Quezon City:`;
      return {
        title: `${category.name} in Quezon City | Hera Wellness Studio`,
        description: `${lead} ${fitNames(treatmentsIn(category.slug).map((t) => t.name), DESC_MAX - lead.length - 1)}`,
        path,
        image: OG(`category-${category.slug}`),
        jsonLd: graph(
          breadcrumbs([['Home', '/'], ['Treatments', '/treatments/'], [category.name, path]]),
          page('CollectionPage', path, `${category.name} in Quezon City`),
          faqJsonLd(categoryFaqs(category), abs(`${path}#faq`)),
          {
            '@type': 'ItemList',
            name: `${category.name} at ${site.name}`,
            itemListElement: treatmentsIn(category.slug).map((t, i) => ({ '@type': 'ListItem', position: i + 1, item: service(t) })),
          },
          business(),
        ),
      };
    }
  }

  if (parts[0] === 'treatments' && parts.length === 3) {
    const t = treatments.find((x) => x.category === parts[1] && x.slug === parts[2]);
    if (t) {
      const category = getCategory(t.category);
      const lead = t.summary ?? t.details ?? `${t.name} is one of the ${category.name.toLowerCase()} at Hera Wellness Studio.`;
      return {
        title: `${t.name} in Quezon City | Hera Wellness Studio`,
        description: describe(lead, [`${t.name} at Hera Wellness Studio, Diliman, Quezon City. Book online.`, 'At Hera Wellness Studio, Quezon City.']),
        path,
        image: ogForTreatment(t),
        jsonLd: graph(
          breadcrumbs([['Home', '/'], ['Treatments', '/treatments/'], [category.name, categoryPath(category.slug)], [t.name, path]]),
          page('WebPage', path, `${t.name} in Quezon City`, { mainEntity: { '@id': serviceId(t) } }),
          service(t),
          faqJsonLd(treatmentFaqs(t), abs(`${path}#faq`)),
          business(),
        ),
      };
    }
  }

  if (path === '/about/') {
    return {
      title: 'About Hera Wellness Studio | Diliman, Quezon City',
      description:
        'Hera Wellness Studio was founded as a sanctuary where beauty, health and self-care meet. Meet the studio in Diliman, Quezon City, and see inside.',
      path,
      image: OG('about'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['About', path]]), page('AboutPage', path, `About ${site.name}`), clinicVideoNode(), studioVideoNode(), organization(), business()),
    };
  }

  if (path === '/reviews/') {
    return {
      title: 'Client Reviews & Video Testimonial | Hera Wellness Studio',
      description: `Watch ${featuredTestimonial.name} share her experience at Hera Wellness Studio — HIFU, HydraFacial and personalized care. Full transcript included.`,
      path,
      image: OG('reviews'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Reviews', path]]), page('WebPage', path, 'Client reviews'), testimonialVideo(), business()),
    };
  }

  if (path === '/contact/') {
    return {
      title: 'Contact & Booking | Hera Wellness Studio, Quezon City',
      description: `Book at Hera Wellness Studio, ${fullAddress}. Request a consultation call or pick a date and time online. Reservations only.`,
      path,
      image: OG('contact'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Contact', path]]), page('ContactPage', path, `Contact ${site.name}`), business()),
    };
  }

  if (path === '/sitemap/') {
    return {
      title: 'Sitemap — All Pages & Treatments | Hera Wellness Studio',
      description: `Every page on the Hera Wellness Studio website: studio information, reviews, contact and all ${treatments.length} treatments.`,
      path,
      image: OG('studio'),
      jsonLd: graph(breadcrumbs([['Home', '/'], ['Sitemap', path]]), page('WebPage', path, 'Sitemap')),
    };
  }

  return {
    title: 'Page not found | Hera Wellness Studio',
    description: 'The page you were looking for could not be found.',
    path,
    noindex: true,
  };
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function renderHead(meta) {
  const url = abs(meta.path);
  const image = abs(meta.image ?? brand.ogImage);
  return [
    `<title>${esc(meta.title)}</title>`,
    `<meta name="description" content="${esc(meta.description)}" />`,
    meta.noindex
      ? '<meta name="robots" content="noindex, follow" />'
      : `<meta name="robots" content="index, follow, max-image-preview:large" />
    <link rel="canonical" href="${url}" />`,
    // Geo-targeting: the studio's location (PH-00 = National Capital Region / Metro Manila).
    '<meta name="geo.region" content="PH-00" />',
    `<meta name="geo.placename" content="${esc(`${site.location.locality}, ${site.location.region}`)}" />`,
    `<meta name="geo.position" content="${site.location.lat};${site.location.lng}" />`,
    `<meta name="ICBM" content="${site.location.lat}, ${site.location.lng}" />`,
    '<meta property="og:type" content="website" />',
    `<meta property="og:site_name" content="${esc(site.name)}" />`,
    `<meta property="og:title" content="${esc(meta.title)}" />`,
    `<meta property="og:description" content="${esc(meta.description)}" />`,
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:image" content="${image}" />`,
    `<meta property="og:image:alt" content="${esc(meta.title)}" />`,
    ...(meta.image ? ['<meta property="og:image:width" content="1200" />', '<meta property="og:image:height" content="630" />'] : []),
    '<meta property="og:locale" content="en_PH" />',
    '<meta name="twitter:card" content="summary_large_image" />',
    `<meta name="twitter:title" content="${esc(meta.title)}" />`,
    `<meta name="twitter:description" content="${esc(meta.description)}" />`,
    `<meta name="twitter:image" content="${image}" />`,
    meta.jsonLd && `<script id="page-jsonld" type="application/ld+json">${JSON.stringify(meta.jsonLd).replace(/</g, '\\u003c')}</script>`,
  ]
    .filter(Boolean)
    .join('\n    ');
}
