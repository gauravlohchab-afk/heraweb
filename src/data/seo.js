// Search results show ~155 characters of a description; longer ones get cut mid-word.
const DESC_MAX = 155;
const clip = (text, max) => {
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  return `${cut.slice(0, cut.lastIndexOf(' ')).replace(/[\s,;:—–-]+$/, '')}…`;
};
// First sentence when the whole text is too long, else a clean word-boundary cut.
const firstSentence = (text) => text.match(/^.+?[.!?](?=\s|$)/)?.[0] ?? text;
/**
 * `lead` plus a tail, trimming only the lead so the tail always survives. Tails
 * are tried longest-first: the first that leaves room for the whole lead (or its
 * whole first sentence) wins; otherwise the lead is cut at a word, with the shortest tail.
 */
const describe = (lead, tails) => {
  const fit = (room) => (lead.length <= room ? lead : firstSentence(lead).length <= room ? firstSentence(lead) : null);
  for (const tail of tails) {
    const body = fit(DESC_MAX - tail.length - 1);
    if (body) return `${body} ${tail}`;
  }
  const tail = tails.at(-1);
  return `${clip(lead, DESC_MAX - tail.length - 1)} ${tail}`;
};
/** "A, B, C and more." — as many names as fit in `room` characters. */
const fitNames = (names, room) => {
  for (let n = names.length; n > 0; n--) {
    const shown = names.slice(0, n);
    const text = n === names.length ? (n > 1 ? `${shown.slice(0, -1).join(', ')} and ${shown.at(-1)}` : shown[0]) : `${shown.join(', ')} and more`;
    if (text.length + 1 <= room) return `${text}.`;
  }
  return '';
};

const website = () => ({ '@type': 'WebSite', '@id': WEBSITE_ID, url: abs('/'), name: site.name, inLanguage: LANG, publisher: { '@id': ORG_ID } });

// 1200×630 social-share images (generated by scripts/og-images.py from the page's own photos).
const OG = (name) => `/images/og/${name}.jpg`;
const TREATMENT_OG = new Set(Object.keys(treatmentMedia));
const ogForTreatment = (t) => (TREATMENT_OG.has(t.slug) ? OG(`treatment-${t.slug}`) : OG(`category-${t.category}`));

const organization = () => ({
  '@type': 'Organization',
  '@id': ORG_ID,
  name: site.name,
  url: abs('/'),
  logo: abs(brand.logo.src),
  email: site.email,
  sameAs: [site.social.facebook, site.social.instagram, site.social.tiktok],
});

const business = () => ({
  '@type': 'BeautySalon',
  '@id': BUSINESS_ID,
  name: site.name,
  description:
    'Hera Wellness Studio is a beauty and wellness studio in Diliman, Quezon City, Metro Manila, offering facial, body and hair treatments with personalized care. Online reservations only.',
  slogan: 'Where beauty meets wellness',
  url: abs('/'),
  logo: abs(brand.logo.src),
  image: abs(brand.ogImage),
  email: site.email,
  parentOrganization: { '@id': ORG_ID },
  address: {
    '@type': 'PostalAddress',
    ...(site.location.street && { streetAddress: site.location.street }),
    addressLocality: site.location.locality,
    addressRegion: site.location.region,
    postalCode: site.location.postalCode,
    addressCountry: site.location.country,
  },
  geo: { '@type': 'GeoCoordinates', latitude: site.location.lat, longitude: site.location.lng },
  hasMap: mapLinkUrl,
  areaServed: [
    { '@type': 'City', name: 'Quezon City' },
    { '@type': 'AdministrativeArea', name: 'Metro Manila' },
  ],
  currenciesAccepted: 'PHP',
  paymentAccepted: 'All payment methods',
  // Lets search engines and AI assistants match the studio to treatment queries.
  knowsAbout: [...categories.map((c) => c.name), ...treatments.flatMap((t) => [t.name, ...(t.aka ?? [])])],
  potentialAction: {
    '@type': 'ReserveAction',
    name: 'Book a treatment',
    target: { '@type': 'EntryPoint', urlTemplate: abs('/contact/'), inLanguage: LANG, actionPlatform: ['https://schema.org/DesktopWebPlatform', 'https://schema.org/MobileWebPlatform'] },
  },
  sameAs: [site.social.facebook, site.social.instagram, site.social.tiktok],
});

const serviceId = (t) => abs(`${treatmentPath(t)}#service`);

const service = (t) => ({
  '@type': 'Service',
  '@id': serviceId(t),
  name: t.name,
  ...(t.aka && { alternateName: t.aka }),
  serviceType: getCategory(t.category).name,
  category: getCategory(t.category).name,
  ...((t.summary || t.details) && { description: [t.summary, t.details].filter(Boolean).join(' ') }),
  url: abs(treatmentPath(t)),
  // Only genuine photos go into structured data.
  ...(t.image && !t.image.generated && { image: abs(t.image.src) }),
  provider: { '@id': BUSINESS_ID },
  areaServed: { '@type': 'City', name: 'Quezon City' },
});

